static rom_error_t owner_verify_app_hybrid_mldsa87_bad_sig_test(void) {
  // Bad ML-DSA signature word.
  g_bad_mldsa_sig = g_test_mldsa_sig;
  g_bad_mldsa_sig.data[0] ^= 0x1;
  uint32_t flash_exec = 0;
  rom_error_t error = owner_verify_app(
      &kHybridAppKey, &kTestEcdsaSig, NULL, &g_test_mldsa_pk, &g_bad_mldsa_sig,
      kTestPrefix1, sizeof(kTestPrefix1), kTestPrefix2, sizeof(kTestPrefix2),
      kTestMsg, sizeof(kTestMsg), &g_test_digest, &flash_exec);
  CHECK(error == kErrorSigverifyBadMldsaSignature);
  CHECK(flash_exec != kSigverifyFlashExec);

  // Non-zero ML-DSA trailing padding byte at offset 4627.
  g_bad_mldsa_sig = g_test_mldsa_sig;
  ((uint8_t *)g_bad_mldsa_sig.data)[kSigverifyMldsa87SigBytes] = 0x01;
  flash_exec = 0;
  error = owner_verify_app(
      &kHybridAppKey, &kTestEcdsaSig, NULL, &g_test_mldsa_pk, &g_bad_mldsa_sig,
      kTestPrefix1, sizeof(kTestPrefix1), kTestPrefix2, sizeof(kTestPrefix2),
      kTestMsg, sizeof(kTestMsg), &g_test_digest, &flash_exec);
  CHECK(error == kErrorSigverifyBadMldsaSignature);
  CHECK(flash_exec != kSigverifyFlashExec);

  // Bad ECDSA signature word.
  ecdsa_p256_signature_t bad_ecdsa = kTestEcdsaSig;
  bad_ecdsa.r[0] ^= 0x1;
  flash_exec = 0;
  error = owner_verify_app(
      &kHybridAppKey, &bad_ecdsa, NULL, &g_test_mldsa_pk, &g_test_mldsa_sig,
      kTestPrefix1, sizeof(kTestPrefix1), kTestPrefix2, sizeof(kTestPrefix2),
      kTestMsg, sizeof(kTestMsg), &g_test_digest, &flash_exec);
  CHECK(error == kErrorSigverifyBadEcdsaSignature);
  CHECK(flash_exec != kSigverifyFlashExec);
  return kErrorOk;
}

static rom_error_t owner_verify_app_hybrid_mldsa87_ok_test(void) {
  uint32_t flash_exec = 0;
  rom_error_t error = owner_verify_app(
      &kHybridAppKey, &kTestEcdsaSig, NULL, &g_test_mldsa_pk, &g_test_mldsa_sig,
      kTestPrefix1, sizeof(kTestPrefix1), kTestPrefix2, sizeof(kTestPrefix2),
      kTestMsg, sizeof(kTestMsg), &g_test_digest, &flash_exec);
  CHECK(error == kErrorOk);
  CHECK(flash_exec == kSigverifyFlashExec);
  return kErrorOk;
}

OTTF_DEFINE_TEST_CONFIG();

bool test_main(void) {
  sec_mmio_init();
  CHECK(otbn_boot_app_load() == kErrorOk);
  memcpy(g_test_mldsa_pk.data, kTestMldsaPkWords, sizeof(g_test_mldsa_pk.data));
  memcpy(g_test_mldsa_sig.data, kTestMldsaSigWords,
         sizeof(g_test_mldsa_sig.data));
  hmac_sha256_init();
  hmac_sha256_update(kTestPrefix1, sizeof(kTestPrefix1));
  hmac_sha256_update(kTestPrefix2, sizeof(kTestPrefix2));
  hmac_sha256_update(kTestMsg, sizeof(kTestMsg));
  hmac_sha256_process();
  hmac_sha256_final(&g_test_digest);

  status_t error = OK_STATUS();

  EXECUTE_TEST(error, owner_verify_spx_signature_not_found_test);
  EXECUTE_TEST(error, owner_verify_bad_spx_config_test);
  EXECUTE_TEST(error, owner_verify_bad_spx_signature_test);
  EXECUTE_TEST(error, owner_verify_rejects_hybrid_mldsa87_test);
  EXECUTE_TEST(error, owner_verify_app_hybrid_mldsa87_not_found_test);
  EXECUTE_TEST(error, owner_verify_app_hybrid_mldsa87_bad_key_test);
  EXECUTE_TEST(error, owner_verify_app_hybrid_mldsa87_bad_sig_test);
  EXECUTE_TEST(error, owner_verify_app_hybrid_mldsa87_ok_test);

  return status_ok(error);
}
